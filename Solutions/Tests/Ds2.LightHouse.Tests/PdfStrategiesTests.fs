[<Fact>]
let ``PdfSignatureClassifier — PR-I2 시점 strategy list = PdfControlSpecStrategy 단독`` () =
    Assert.Equal(1, List.length PdfSignatureClassifier.strategies)
    Assert.Equal("PdfControlSpecStrategy", PdfSignatureClassifier.strategies.Head.Name)

