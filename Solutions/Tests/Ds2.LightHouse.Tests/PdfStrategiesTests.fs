[<Fact>]
let ``PdfControlSpecStrategy Build — 매치 시 markdown 반환 + 머리말 5행 강제`` () =
    let extracted = makeControlSpecFixture ()
    let strategy = PdfControlSpecStrategy() :> IPdfStrategy
    let dummyPath = "fixture.pdf"
    match strategy.Build (dummyPath, extracted) with
    | StrategyOutcome.Rejected entry ->
        Assert.Fail(sprintf "Build 가 Rejected 반환 — reason=%s" entry.Reason)
    | StrategyOutcome.Built markdown ->
        let lines = markdown.Split([| '\n' |], 8)
        Assert.True(lines.Length >= 5, "최소 5 행 머리말 필요")
        Assert.Contains("generated by PdfControlSpecStrategy v", lines.[0])
        Assert.Contains("source: fixture.pdf", lines.[1])
        Assert.Contains("docId:", lines.[1])
        Assert.Contains("signature: PdfControlSpecStrategy:", lines.[2])
        Assert.Contains("estimated-tokens:", lines.[3])
        Assert.Contains("strategy-version: PdfControlSpecStrategy v", lines.[4])

[<Fact>]
