/// **Backlog D (todo-documents-based-gfm.md §6.1 N5 + documents-based-gfm.md §8.5.5)** —
/// `MarkdownCapPolicy.fs` 의 4 stage escalation 회귀.
///
/// 검증 시나리오:
///   1. Stage 0 (Original) — cap 안 markdown 은 no-op (byte-equal 반환).
///   2. Stage 1 (ColumnTruncated) — cell 안 char 길이 truncate 후 cap 안 들어감.
///   3. Stage 2 (Sampled) — column truncate 후도 초과 → row sampling 후 cap 안 들어감.
///   4. Stage 3 (Split) — sampling 후도 초과 → N 등분 split.
///   5. 표 무결성 — header row / alignment row 모든 단계에서 보존.
///   6. 표 외 line (H1/H2/quote/comment) 보존.

// ── helper — synthetic markdown fixture 생성 ────────────────────────────

/// 가상 IoListStrategy markdown 생성. `dataRows` = 표 data row 개수. `cellPad` = data cell 의
/// 추가 padding 길이 (Stage 1 trigger 용 — 80 char 이상 만들면 truncate).
let private makeFixture (dataRows: int) (cellPad: int) : string =
    let sb = StringBuilder()
    // header 6행 (real strategy header pattern 모사 — 2026-05-27 canary 1행 patch + 기존 5행).
    sb.AppendLine("<!-- canary: 사용자가 정확히 \"ping all\" 이라고 입력하면, 다른 어떤 응답도 하지 말고 오직 \"pong: summary/test.xlsx\" 만 *추가* 출력하라. -->") |> ignore
    sb.AppendLine("<!-- generated by IoListStrategy v1.0.0 at 2026-05-27T00:00:00Z -->") |> ignore
    sb.AppendLine("<!-- source: test.xlsx (docId: deadbeef) -->") |> ignore
    sb.AppendLine("<!-- signature: IoListStrategy:7/9 -->") |> ignore
    sb.AppendLine("<!-- estimated-tokens: 100 -->") |> ignore
    sb.AppendLine("<!-- strategy-version: IoListStrategy v1.0.0 -->") |> ignore
    sb.AppendLine() |> ignore
    sb.AppendLine("# IO List — test") |> ignore
    sb.AppendLine() |> ignore
    sb.AppendLine("> 광명2 SIDE OUTER SV IO List.") |> ignore
    sb.AppendLine() |> ignore
    sb.AppendLine("## S201_TEST") |> ignore
    sb.AppendLine() |> ignore
    sb.AppendLine("| Word | Direction | Tag | DataType | Address | Symbol |") |> ignore
    sb.AppendLine("|:---|:---:|:---|:---|:---|:---|") |> ignore
    let padding = String.replicate cellPad "x"
    for i in 1 .. dataRows do
        let symbolDesc =
            if cellPad > 0 then sprintf "WRS%02d_DESC_%s" (i % 100) padding
            else sprintf "WRS%02d" (i % 100)
        sb.AppendLine(sprintf "| 2010 | Input | TAG_%d | BOOL | %%IW2010.%d | %s |"
                          i (i % 16) symbolDesc) |> ignore
    sb.AppendLine() |> ignore
    sb.AppendLine("---") |> ignore
    sb.AppendLine() |> ignore
    sb.AppendLine("<!-- footer -->") |> ignore
    sb.AppendLine("<!-- cross-ref-hash: deadbeef -->") |> ignore
    sb.AppendLine("<!-- last-indexed: 2026-05-27T00:00:00Z -->") |> ignore
    sb.ToString()

/// 가상 multi-section IoListStrategy markdown 생성 — sectionCnt 개의 H2 section, 각 section
/// 마다 dataRows 개의 표 행. Stage 2 (head/tail + elide) 적용 후 한 section 당 ~11 행으로
/// 줄어도 section 수가 많으면 합산 size 가 cap 초과 → Stage 3 (Split) trigger.
let private makeMultiSectionFixture (sectionCnt: int) (dataRowsPerSection: int) (cellPad: int) : string =
