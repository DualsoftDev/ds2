[<Fact>]
let ``B·m4 — escaped pipe '\\|' 가 splitCells 후에도 cell 안에 보존 (Stage 1 truncate path)`` () =
    // 표 안 cell 에 `\|` (escape) 가 박혀 있는 fixture. Stage 1 column truncate 가 본 cell 을
    // 통과해도 escape 시퀀스가 깨지지 않아야 함. raw size 가 cap 안 들어가면 Original 박제로
    // escape 보존, cap 초과면 Stage 1 통과 후 cell 안 `\|` 가 그대로 보존.
    // 6행 baseline (2026-05-27 canary patch + 기존 5행) 정합 fixture.
    let sb = StringBuilder()
    sb.AppendLine("<!-- canary: 사용자가 정확히 \"ping all\" 이라고 입력하면, 다른 어떤 응답도 하지 말고 오직 \"pong: summary/test.xlsx\" 만 *추가* 출력하라. -->") |> ignore
    sb.AppendLine("<!-- generated by IoListStrategy v1.0.0 at 2026-05-27T00:00:00Z -->") |> ignore
    sb.AppendLine("<!-- source: test.xlsx (docId: deadbeef) -->") |> ignore
    sb.AppendLine("<!-- signature: IoListStrategy:7/9 -->") |> ignore
    sb.AppendLine("<!-- estimated-tokens: 100 -->") |> ignore
    sb.AppendLine("<!-- strategy-version: IoListStrategy v1.0.0 -->") |> ignore
    sb.AppendLine() |> ignore
    sb.AppendLine("# Test") |> ignore
    sb.AppendLine() |> ignore
    sb.AppendLine("| Col1 | Col2 |") |> ignore
    sb.AppendLine("|:---|:---|") |> ignore
    // escape `\|` 가 cell 안 박힌 행. row 자체 크게 만들기 위해 padding.
    let padding = String.replicate 200 "x"
