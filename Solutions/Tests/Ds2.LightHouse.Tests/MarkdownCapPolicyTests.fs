// ── G·G-Minor-1 (Outlier/Minor 묶음 1) — cap boundary fixture 회귀 ───────

/// 정확히 `targetBytes` byte 의 markdown 박제 helper — 표 구조 가진 strategy markdown 의
/// 마지막 row 들이 ASCII padding 으로 정확 size 채워짐 (Stage 1/2 escalation 가능).
let private makeSizedTableFixture (targetBytes: int) : string =
    // baseline header + 표 alignment + footer 박제 후 data row 로 정확 size 맞추기.
    let header =
        // **canary 박제 제외 (의도된 ASCII-only fixture)**: 본 makeSizedTableFixture 는 정확 byte
        // boundary 회귀용 — `sb.Length` (char count) 기반 size 계산이 multi-byte UTF-8 (canary 안
        // Korean) 박제 시 char-vs-byte drift 로 cap 40+ byte 초과 발생. boundary 검증 의도 우선 →
        // canary 박제 skip. strategy header 정합 검증은 본 fixture 의도 외 (StrategyMarkdownTests 가 담당).
        "<!-- generated by IoListStrategy v1.0.0 at 2026-05-27T00:00:00Z -->\n"
        + "<!-- source: test.xlsx (docId: deadbeef) -->\n"
        + "<!-- signature: IoListStrategy:7/9 -->\n"
        + "<!-- estimated-tokens: 100 -->\n"
        + "<!-- strategy-version: IoListStrategy v1.0.0 -->\n"
        + "\n"
        + "# Test\n\n"
        + "| A | B |\n"
        + "|:---|:---|\n"
    let footer =
        "\n---\n\n"
        + "<!-- footer -->\n"
        + "<!-- cross-ref-hash: deadbeef -->\n"
        + "<!-- last-indexed: 2026-05-27T00:00:00Z -->\n"
    let row (i: int) = sprintf "| a%d | b%d |\n" i i
    let sb = StringBuilder()
    sb.Append header |> ignore
    let mutable i = 1
    let footerSize = Encoding.UTF8.GetByteCount footer
    while sb.Length + footerSize < targetBytes - 30 do
        sb.Append (row i) |> ignore
        i <- i + 1
    // fine-tune with padding row to reach exact size.
    let currentBytes () = Encoding.UTF8.GetByteCount(sb.ToString()) + footerSize
    let remaining = targetBytes - currentBytes ()
    if remaining > 0 then
        // padding row `| x... | y |\n` 형식. cell 안 padding 길이 조정.
        let prefix = "| "
        let mid = " | y |\n"
        let baseLen = prefix.Length + mid.Length
        let padLen = max 0 (remaining - baseLen)
        sb.Append prefix |> ignore
        sb.Append (String.replicate padLen "x") |> ignore
        sb.Append mid |> ignore
    sb.Append footer |> ignore
    sb.ToString()

[<Fact>]
let ``G·G-Minor-1 — size <= MaxMarkdownBytes boundary 는 Original 반환`` () =
    let md = makeSizedTableFixture MarkdownCapPolicy.MaxMarkdownBytes
    let sz = utf8Size md
    Assert.True(sz <= MarkdownCapPolicy.MaxMarkdownBytes,
        sprintf "fixture size %d 가 cap %d 안 (boundary)" sz MarkdownCapPolicy.MaxMarkdownBytes)
    let result = MarkdownCapPolicy.applyCap md
    Assert.Equal(MarkdownCapPolicy.Original, result.Stage)
    Assert.Equal(md, result.Markdown)

[<Fact>]
let ``G·G-Minor-1 — size > MaxMarkdownBytes boundary 는 escalation 진입`` () =
    // boundary 직상 — 표 구조 있는 fixture → Stage 1 truncate 흡수 가능.
    let md = makeSizedTableFixture (MarkdownCapPolicy.MaxMarkdownBytes + 100)
    Assert.True(utf8Size md > MarkdownCapPolicy.MaxMarkdownBytes)
    let result = MarkdownCapPolicy.applyCap md
    Assert.NotEqual(MarkdownCapPolicy.Original, result.Stage)
    Assert.True(result.SizeBytes <= MarkdownCapPolicy.MaxMarkdownBytes)

// ── B·M3 (Outlier/Minor 묶음 1) — split note 위치 회귀 ─────────────────

[<Fact>]
let ``B·M3 — Stage 3 split note 는 머리말 6행 다음 + H1 이전 박제`` () =
    let md = makeMultiSectionFixture 800 20 0
    let result = MarkdownCapPolicy.applyCap md
    match result.SplitParts with
    | Some parts ->
        for part in parts do
            let lines = part.Split([| '\n' |]) |> Array.map (fun l -> l.TrimEnd('\r'))
            // 첫 6행은 머리말 (2026-05-27 canary patch — canary line 1 + 기존 5행 = line 2~6).
            Assert.StartsWith("<!-- canary:", lines.[0])
            Assert.StartsWith("<!-- generated by", lines.[1])
            Assert.StartsWith("<!-- source:", lines.[2])
            Assert.StartsWith("<!-- signature:", lines.[3])
            Assert.StartsWith("<!-- estimated-tokens:", lines.[4])
            Assert.StartsWith("<!-- strategy-version:", lines.[5])
            // 7번째 line 은 blank, 8번째 line 이 split note (또는 머리말 직후 첫 non-blank).
            // split note 가 머리말 안 (lines.[0..5]) 어느 위치에도 박제되어 있으면 안 됨.
            for i in 0 .. 5 do
                Assert.DoesNotContain("<!-- split: part", lines.[i])
            // split note 가 H1 (`# `) 보다 앞에 있어야 함.
            let splitIdx =
                lines
                |> Array.tryFindIndex (fun l -> l.StartsWith("<!-- split: part"))
            let h1Idx =
                lines
                |> Array.tryFindIndex (fun l -> l.StartsWith("# "))
            match splitIdx, h1Idx with
            | Some s, Some h ->
                Assert.True(s < h,
                    sprintf "split note 위치 (line %d) 가 H1 (line %d) 보다 앞" s h)
            | None, _ -> Assert.Fail("split note 박제 누락")
            | _, None -> ()  // H1 부재 fixture — split note 박제 자체만 확인.
    | None -> Assert.Fail("Stage 3 진입 미흡 — SplitParts = None")

