/// **PR-N15 (todo-documents-based-gfm.md §6.1 N15 + documents-based-gfm.md §8.5.4 / §8.5.5)** —
/// `UserGuideImporter.importAll` 회귀.
///
/// 검증 시나리오:
///   1. happy path: 단일 `<root>/guide/foo.md` → `_user-guide-foo.md` 박제 + 머리말 6행 + 본문 보존.
///   2. 재귀 sweep: `<root>/guide/sub/foo.md` → `_user-guide-sub-foo.md`.
///   3. 빈 디렉토리: no-op (빈 array).
///   4. 부재 디렉토리: no-op (예외 0).
///   5. cross-ref-hash 정확 — 동일 source bytes 재호출 시 hash 동일.
///   6. 멱등 — 동일 source 2회 호출 byte-identical 본문 (단 generated-at 만 갱신).
///   7. 머리말 6행 정확 형식 — 각 행 정합 assert.
///   8. SpecializedDigestBuilder ordering 회귀 — `_user-guide-*` 가 underscore prefix 로 맨 앞 박제.

// ── 공통 helpers ────────────────────────────────────────────────────────

let private withTempDir (action: string -> 'r) : 'r =
    let dir = Path.Combine(Path.GetTempPath(), sprintf "lh-ugimp-%s" (Guid.NewGuid().ToString("N")))
    Directory.CreateDirectory dir |> ignore
    try action dir
    finally
        try Directory.Delete(dir, true) with _ -> ()

let private writeGuide (root: string) (relativePath: string) (content: string) : string =
    let path = Path.Combine(root, "guide", relativePath)
    Directory.CreateDirectory(Path.GetDirectoryName path) |> ignore
    File.WriteAllText(path, content, UTF8Encoding(false))
    path

let private sha256Hex (s: string) : string =
    use sha = SHA256.Create()
    let bytes = Encoding.UTF8.GetBytes(s: string)
    let hash = sha.ComputeHash(bytes)
    let sb = StringBuilder(hash.Length * 2)
    for b in hash do sb.Append(b.ToString("x2")) |> ignore
    sb.ToString()

// ── 시나리오 1: happy path 단일 markdown ───────────────────────────────

[<Fact>]
let ``importAll - 단일 guide markdown 박제 + 머리말 6행 + 본문 보존`` () =
    withTempDir (fun root ->
        let body = "# 사용자 가이드\n\n본 문서는 ***REDACTED***2 색인 우선순위 박제 가이드."
        writeGuide root "foo.md" body |> ignore
        let results = UserGuideImporter.importAll root
        Assert.Equal(1, results.Length)
        let outPath = results.[0]
        Assert.EndsWith("_user-guide-foo.md", outPath.Replace('\\', '/'))
        let written = File.ReadAllText(outPath, Encoding.UTF8)
        // 본문 박제 확인.
        Assert.Contains(body, written)
        // 머리말 6행 + 빈 행 1 → 본문 시작 = line 8 부터.
        let lines = written.Replace("\r\n", "\n").Split('\n')
        Assert.True(lines.Length >= 7, sprintf "박제 line 수 부족: %d" lines.Length)
        Assert.StartsWith("<!-- canary:", lines.[0])
        Assert.Contains("pong: guide/foo.md", lines.[0])
        Assert.StartsWith("<!-- generated by UserGuideImporter v1.0 at ", lines.[1])
        Assert.StartsWith("<!-- source: guide/foo.md (cross-ref-hash: ", lines.[2])
        Assert.Equal("<!-- signature: userGuide:1/1 -->", lines.[3])
        Assert.StartsWith("<!-- estimated-tokens: ", lines.[4])
        Assert.Equal("<!-- strategy-version: UserGuideImporter v1.0 -->", lines.[5])
        Assert.Equal("", lines.[6]))  // 머리말 직후 빈 행.

// ── 시나리오 2: 재귀 sweep + subdir 박제 ─────────────────────────────

[<Fact>]
let ``importAll - subdir 재귀 sweep + dash 치환 박제`` () =
    withTempDir (fun root ->
        writeGuide root "top.md" "# Top" |> ignore
        writeGuide root (Path.Combine("sub", "nested.md")) "# Nested" |> ignore
        writeGuide root (Path.Combine("sub", "deep", "leaf.md")) "# Leaf" |> ignore

        let results = UserGuideImporter.importAll root |> Array.map (fun p -> Path.GetFileName p)
        Assert.Equal(3, results.Length)
        let resultSet = Set.ofArray results
        Assert.Contains("_user-guide-top.md", resultSet)
        Assert.Contains("_user-guide-sub-nested.md", resultSet)
        Assert.Contains("_user-guide-sub-deep-leaf.md", resultSet))

