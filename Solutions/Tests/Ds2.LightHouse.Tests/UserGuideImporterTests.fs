// ── 시나리오 5: cross-ref-hash 정확 ──────────────────────────────────

[<Fact>]
let ``importAll - cross-ref-hash 가 source bytes SHA256 정합`` () =
    withTempDir (fun root ->
        let body = "abc123 한글 본문 hash 검증"
        writeGuide root "h.md" body |> ignore
        let results = UserGuideImporter.importAll root
        let written = File.ReadAllText(results.[0], Encoding.UTF8)
        let expectedHash = sha256Hex body
        Assert.Contains(sprintf "cross-ref-hash: %s" expectedHash, written))

// ── 시나리오 6: 멱등 ─────────────────────────────────────────────────

[<Fact>]
let ``importAll - 동일 source 재호출 시 본문 byte-identical (generated-at 행만 갱신)`` () =
    withTempDir (fun root ->
        let body = "# Idempotent\n\nstatic content"
        writeGuide root "idem.md" body |> ignore
        let r1 = UserGuideImporter.importAll root
        let c1 = File.ReadAllText(r1.[0], Encoding.UTF8)
        // 시간 차이 확보 위해 짧은 sleep (generated-at 이 다를 수 있게).
        System.Threading.Thread.Sleep(50)
        let r2 = UserGuideImporter.importAll root
        let c2 = File.ReadAllText(r2.[0], Encoding.UTF8)
        Assert.Equal(r1.[0], r2.[0])
        // 본문 + cross-ref-hash 동일 — generated-at line 2 만 다를 수 있음.
        let lines1 = c1.Replace("\r\n", "\n").Split('\n')
        let lines2 = c2.Replace("\r\n", "\n").Split('\n')
        Assert.Equal(lines1.[0], lines2.[0])  // canary
        Assert.Equal(lines1.[2], lines2.[2])  // source + cross-ref-hash
        Assert.Equal(lines1.[3], lines2.[3])  // signature
        Assert.Equal(lines1.[4], lines2.[4])  // estimated-tokens
        Assert.Equal(lines1.[5], lines2.[5])  // strategy-version
        // 본문 (line 7 이후) 도 동일.
        let body1 = String.Join("\n", lines1 |> Array.skip 7)
        let body2 = String.Join("\n", lines2 |> Array.skip 7)
        Assert.Equal(body1, body2))

// ── 시나리오 7: SpecializedDigestBuilder ordering 회귀 ────────────────

[<Fact>]
let ``SpecializedDigestBuilder - _user-guide-* 가 underscore prefix 로 alphabetical 맨 앞 박제`` () =
    withTempDir (fun root ->
        // strategy 산출물 fixture — `b1-iolist-...md` (b1 prefix 가 underscore 보다 뒤).
        let summary = TextDumper.summaryDir root
        Directory.CreateDirectory summary |> ignore
        File.WriteAllText(Path.Combine(summary, "b1-iolist.md"), "# B1 IoList", UTF8Encoding(false))
        // user-guide 박제 직전에 strategy 산출물이 이미 박제된 상태 가정.
        writeGuide root "intro.md" "# User Guide Intro" |> ignore
        let userGuideOuts = UserGuideImporter.importAll root
        Assert.Equal(1, userGuideOuts.Length)

        let digest = SpecializedDigestBuilder.build root
        Assert.Equal(2, digest.Metadata.FileCount)
        // `_user-guide-intro.md` 가 `b1-iolist.md` 보다 먼저 박제 (ASCII '_'=0x5F < 'b'=0x62).
        let idxUserGuide = digest.Combined.IndexOf("User Guide Intro")
        let idxIoList = digest.Combined.IndexOf("B1 IoList")
        Assert.True(idxUserGuide >= 0)
        Assert.True(idxIoList >= 0)
        Assert.True(idxUserGuide < idxIoList,
            sprintf "_user-guide-* 가 맨 앞 박제 의무 (idxUserGuide=%d, idxIoList=%d)" idxUserGuide idxIoList))

