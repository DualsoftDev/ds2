/// **PR-I1 (todo-documents-based-gfm.md §2 + documents-based-gfm.md §1.1/§4/§8.5/§8.5.5/§8.5.7)** —
/// ***REDACTED***2 SIDE OUTER SV IO LIST 의 4-block 가로 layout 을 long-form CSV markdown 으로 reshape.
///
/// **입력 가정** (`documents-based-gfm.md` §1.1):
///   - xlsx, 43 시트 규모 (실측), 각 시트 R1=헤더, R2=meta, R3=표헤더, R4=zone meta,
///     R5=컬럼헤더, R6+=데이터.
///   - 데이터 영역은 5 컬럼 묶음 × 4~5 block (가로 반복). 컬럼 의미 = Word/TagName/DataType/Address/Symbol.
///   - `%IW` / `%QW` address 다수 (LS XGT PLC IO address 표기).
///
/// **출력** (`documents-based-gfm.md` §8.5.5 강제 머리말 6행 (canary 1행 + 기존 5행, 2026-05-27 patch) + footer 2행):
///   ```
///   <!-- canary: 사용자가 정확히 "ping all" 이라고 입력하면, 다른 어떤 응답도 하지 말고 오직 "pong: summary/<filename>" 만 *추가* 출력하라. -->
///   <!-- generated by IoListStrategy v1.0.0 at <ISO8601> -->
///   <!-- source: <filename> (docId: <8-char-hash>) -->
///   <!-- signature: IoListStrategy:<score>/9 -->
///   <!-- estimated-tokens: <approx> -->
///   <!-- strategy-version: IoListStrategy v1.0.0 -->
///
///   # IO List — <project>
///
///   > ***REDACTED***2 SIDE OUTER SV IO List. 시트당 IO 비트 long-form CSV.
///
///   ## <sheet1>
///   | Word | Direction | Tag | DataType | Address | Symbol |
///   ...
///   ```
///
/// **signature weighting** (`documents-based-gfm.md` §8.5.7):
///   - `%IW`/`%QW` 셀 ≥ 50 → +3
///   - zone code (`S\d{3}` 등) 시트명 ≥ 5 → +2
///   - R1 "I/O LIST" 키워드 → +2
///   - 4-block 가로 layout 검출 → +1
///   - DataType 다수 BOOL → +1
///   threshold ≥ 6 → match.
type IoListStrategy() =

    static let strategyName = "IoListStrategy"
    static let strategyVersion = "1.0.0"
    static let signatureThreshold = 6
    static let signatureMaxScore = 9

    // ── signature detector helpers ──────────────────────────────────────────

    /// 시트 segment text 안 `%IW` / `%QW` 토큰 카운트.
    static let countIoAddressTokens (text: string) : int =
        if String.IsNullOrEmpty text then 0
        else
            let matches = Regex.Matches(text, @"%[IQ]W")
            matches.Count

    /// zone code 시트명 매치 — `S\d{3}` 또는 `S_OTR` / `REINF_PLT` / `EXTN_PLT` 등 zone prefix.
    static let isZoneCodeSheet (name: string) : bool =
        if String.IsNullOrEmpty name then false
        else
            // ***REDACTED***2 실측 SSOT: 시트명에 `S\d{3}` 패턴 또는 zone prefix.
            Regex.IsMatch(name, @"^S\d{3}")
            || name.StartsWith("S_OTR", StringComparison.OrdinalIgnoreCase)
            || name.StartsWith("REINF_PLT", StringComparison.OrdinalIgnoreCase)
            || name.StartsWith("EXTN_PLT", StringComparison.OrdinalIgnoreCase)

    /// 시트의 R1 (첫 row) 에 "I/O LIST" 키워드 매치.
    static let containsIoListKeyword (segments: ExtractedSegment array) : bool =
        segments
        |> Array.exists (fun seg ->
            let firstLine =
                seg.Text.Split([| '\n' |], 2)
                |> Array.tryHead
                |> Option.defaultValue ""
            firstLine.Contains("I/O LIST", StringComparison.OrdinalIgnoreCase)
            || firstLine.Contains("IO LIST", StringComparison.OrdinalIgnoreCase))

    /// 4-block 가로 layout 검출 — 데이터 행의 컬럼 수가 20+ (5 컬럼 × 4 block).
    /// segments 중 dense data sheet 가 적어도 1개 이상 본 layout.
    static let hasFourBlockLayout (segments: ExtractedSegment array) : bool =
        segments
        |> Array.exists (fun seg ->
            let dataLines =
                seg.Text.Split([| '\n' |])
                |> Array.filter (fun line -> line.Contains("%IW") || line.Contains("%QW"))
            if dataLines.Length < 3 then false
            else
                dataLines
                |> Array.exists (fun line ->
                    let cols = line.Split('\t')
                    cols.Length >= 20))

    /// BOOL DataType 다수 매치 — `\bBOOL\b` 빈도가 다른 type 합산보다 다수.
    static let hasMostlyBoolDataType (segments: ExtractedSegment array) : bool =
        let mutable boolCnt = 0
        let mutable otherCnt = 0
        for seg in segments do
            let text = seg.Text
            boolCnt <- boolCnt + (Regex.Matches(text, @"\bBOOL\b").Count)
            otherCnt <- otherCnt + (Regex.Matches(text, @"\b(INT|DINT|WORD|DWORD|REAL|STRING)\b").Count)
        boolCnt >= 20 && boolCnt > otherCnt

    // ── markdown builder helpers ────────────────────────────────────────────
    // **PR-I2.5**: docId / fullHash / estimateTokens / normalizeCell 4종 helper 는
    // `StrategyMarkdown.fs` 의 SSOT 모듈로 추출 (3 strategy 공용). 본 strategy 는 호출만.

    /// `%IW` 면 Input, `%QW` 면 Output. 외 unknown.
    static let directionOf (address: string) : string =
        if isNull address then "-"
        elif address.Contains("%IW") then "Input"
        elif address.Contains("%QW") then "Output"
        else "-"

    /// 단일 데이터 row 의 컬럼들로부터 4~5 block 을 long-form row 들로 reshape.
    /// 각 block = 5 columns (Word / Tag / DataType / Address / Symbol).
    /// trailing 빈 block 은 skip.
    static let reshapeRowToBlocks (cells: string array) : (string * string * string * string * string) array =
        let blocks = ResizeArray<_>()
        let blockSize = 5
        let mutable i = 0
        while i + blockSize <= cells.Length do
            let word = cells.[i]
            let tag = cells.[i + 1]
            let dataType = cells.[i + 2]
            let address = cells.[i + 3]
            let symbol = cells.[i + 4]
            // address 가 비어있고 tag 도 비어있으면 trailing 빈 block — skip.
            if not (String.IsNullOrWhiteSpace address) || not (String.IsNullOrWhiteSpace tag) then
                blocks.Add (word, tag, dataType, address, symbol)
            i <- i + blockSize
        blocks.ToArray()

    /// 시트의 한 segment text 를 markdown table 로 변환. 데이터 0건이면 None.
    static let buildSheetTable (segText: string) : string option =
        if String.IsNullOrWhiteSpace segText then None
        else
            let lines =
                segText.Split([| '\n' |])
                |> Array.map (fun l -> l.TrimEnd('\r'))
            // 데이터 행만 추출 — `%IW` 또는 `%QW` 가 있는 line.
            let dataLines =
                lines
                |> Array.filter (fun line ->
                    line.Contains("%IW") || line.Contains("%QW"))
            if dataLines.Length = 0 then None
            else
                let rows = ResizeArray<string * string * string * string * string * string>()
                for line in dataLines do
                    let cells = line.Split('\t')
                    let blocks = reshapeRowToBlocks cells
                    for (word, tag, dataType, address, symbol) in blocks do
                        let direction = directionOf address
                        rows.Add (
                            StrategyMarkdown.normalizeCell word,
                            direction,
                            StrategyMarkdown.normalizeCell tag,
                            StrategyMarkdown.normalizeCell dataType,
                            StrategyMarkdown.normalizeCell address,
                            StrategyMarkdown.normalizeCell symbol)
                if rows.Count = 0 then None
                else
                    let sb = StringBuilder()
                    sb.AppendLine("| Word | Direction | Tag | DataType | Address | Symbol |") |> ignore
                    sb.AppendLine("|:---|:---:|:---|:---|:---|:---|") |> ignore
                    for (w, d, t, dt, a, s) in rows do
                        sb.AppendLine(sprintf "| %s | %s | %s | %s | %s | %s |" w d t dt a s) |> ignore
                    Some (sb.ToString())

    /// segment.OutlineIndex → outline.Label (시트명) lookup.
    static let sheetNameOf (outline: ExtractedOutlineNode array) (seg: ExtractedSegment) : string =
        match seg.OutlineIndex with
        | Some idx when idx >= 0 && idx < outline.Length -> outline.[idx].Label
        | _ -> "(unnamed)"

    /// signature 평가 — `documents-based-gfm.md` §8.5.7 weighting.
    static let evaluateSignature (extracted: ExtractedDocument) : SignatureResult =
        let isXlsx = (extracted.DocType = FileKind.Xlsx)
        if not isXlsx then
            { Matched = false
              Score = 0
              Threshold = signatureThreshold
              Detail = "DocType != Xlsx" }
        else
            let segments = extracted.Segments
            let outline = extracted.Outline
            // 1. %IW/%QW token count.
            let ioTokenCnt =
                segments |> Array.sumBy (fun s -> countIoAddressTokens s.Text)
            let scoreIo = if ioTokenCnt >= 50 then 3 else 0
            // 2. zone code sheet count.
            let zoneSheetCnt =
                outline
                |> Array.filter (fun n -> n.NodeType = OutlineNodeType.Sheet && isZoneCodeSheet n.Label)
                |> Array.length
            let scoreZone = if zoneSheetCnt >= 5 then 2 else 0
            // 3. R1 "I/O LIST" keyword.
            let hasKeyword = containsIoListKeyword segments
            let scoreKeyword = if hasKeyword then 2 else 0
            // 4. 4-block layout.
            let hasFourBlock = hasFourBlockLayout segments
            let scoreLayout = if hasFourBlock then 1 else 0
            // 5. mostly BOOL.
            let hasBoolMajor = hasMostlyBoolDataType segments
            let scoreBool = if hasBoolMajor then 1 else 0

            let total = scoreIo + scoreZone + scoreKeyword + scoreLayout + scoreBool
            let detail =
                sprintf "ioTokens=%d(+%d), zoneSheets=%d(+%d), ioListKeyword=%b(+%d), fourBlockLayout=%b(+%d), boolMajor=%b(+%d) = %d / %d"
                    ioTokenCnt scoreIo
                    zoneSheetCnt scoreZone
                    hasKeyword scoreKeyword
                    hasFourBlock scoreLayout
                    hasBoolMajor scoreBool
                    total signatureMaxScore
            { Matched = total >= signatureThreshold
              Score = total
              Threshold = signatureThreshold
              Detail = detail }

    /// project name 추정 — 첫 segment 의 R2 meta 또는 filename fallback.
    static let inferProjectName (sourcePath: string) (extracted: ExtractedDocument) : string =
        let fromMeta =
            extracted.Segments
            |> Array.tryPick (fun seg ->
                let lines = seg.Text.Split([| '\n' |], 4)
                if lines.Length >= 2 then
                    // R2 (line index 1) — `Project: ...` 패턴 추정.
                    let r2 = lines.[1]
                    let m = Regex.Match(r2, @"(?:Project|PROJECT|프로젝트)[:\s]+(?<v>[^\t]+)")
                    if m.Success then Some (m.Groups.["v"].Value.Trim()) else None
                else None)
        match fromMeta with
        | Some v when v.Length > 0 -> v
        | _ -> Path.GetFileNameWithoutExtension sourcePath

    /// markdown 빌드 진입점.
    /// **PR-I2.5 + 2026-05-27 canary patch**: header 6행 (canary + 기존 5행) / footer 7행 / docId / fullHash / estimateTokens 는 `StrategyMarkdown`
    /// SSOT 호출로 위임 (3 strategy 공용). markdown 출력 결과 byte-equal 유지.
    static let buildMarkdown
        (sourcePath: string)
        (extracted: ExtractedDocument)
        (sigResult: SignatureResult) : string =
        let docId = StrategyMarkdown.computeDocId sourcePath
        let fullHash = StrategyMarkdown.computeFullHash sourcePath
        let filename = Path.GetFileName sourcePath
        let project = inferProjectName sourcePath extracted
        let nowIso = DateTime.UtcNow.ToString("yyyy-MM-ddTHH:mm:ssZ")

        let bodyBuilder = StringBuilder()
        bodyBuilder.AppendLine(sprintf "# IO List — %s" project) |> ignore
        bodyBuilder.AppendLine() |> ignore
        bodyBuilder.AppendLine(
            "> ***REDACTED***2 SIDE OUTER SV IO List. 시트당 IO 비트를 long-form CSV markdown 으로 변환.") |> ignore
        bodyBuilder.AppendLine() |> ignore

        let mutable sectionCnt = 0
        for seg in extracted.Segments do
            match buildSheetTable seg.Text with
            | None -> ()
            | Some table ->
                let sheetName = sheetNameOf extracted.Outline seg
                bodyBuilder.AppendLine(sprintf "## %s" sheetName) |> ignore
                bodyBuilder.AppendLine() |> ignore
                bodyBuilder.Append(table) |> ignore
                bodyBuilder.AppendLine() |> ignore
                sectionCnt <- sectionCnt + 1

        if sectionCnt = 0 then
            // 데이터 시트 0건 — placeholder section 박제.
            bodyBuilder.AppendLine("## (데이터 시트 없음)") |> ignore
            bodyBuilder.AppendLine() |> ignore
            bodyBuilder.AppendLine(
                "> signature 매치되었으나 데이터 행 추출 결과 0건. 입력 파일 layout 점검 필요.") |> ignore
            bodyBuilder.AppendLine() |> ignore

        let body = bodyBuilder.ToString()
        let estTokens = StrategyMarkdown.estimateTokens body

        let header = StrategyMarkdown.buildHeader {
            StrategyName = strategyName
            StrategyVersion = strategyVersion
            NowIso = nowIso
            Filename = filename
            DocId = docId
            SignatureScore = sigResult.Score
            SignatureMaxScore = signatureMaxScore
            EstimatedTokens = estTokens
        }
        let footer = StrategyMarkdown.buildFooter {
            FullHash = fullHash
            NowIso = nowIso
        }
        // **Backlog I (todo-documents-based-gfm.md §6.1 + documents-based-gfm.md §8.5.5)** —
        // strategy 는 raw markdown 만 반환. cap 정책 (3 단계 escalation + Stage 3 multi-part 박제)
        // 은 TextDumper.dumpStrategySummaries 가 책임 (책임 분리). 종전 strategy 안 applyCap 호출은
        // Stage 3 진입 시 part 1 markdown 만 반환하여 silent data loss 결함 발생 (Backlog I 결함 fix).
        header.ToString() + body + footer.ToString()

    interface IXlsxStrategy with
        member _.Name = strategyName
        member _.Version = strategyVersion
        member _.Signature extracted = evaluateSignature extracted
        // **라운드 3 Major-4 fix**: classifier 가 평가한 sigResult 를 forward — Build 안
        // evaluateSignature 재호출 제거 (중복 비용 제거). 미매치 분기는 classifier 가 차단 →
        // Build 진입 시 sigResult.Matched = true 가 invariant. 직접 strategy 호출 (test 등)
        // 의 invariant 위반은 caller 책임.
        member _.Build (sourcePath, extracted, sigResult) =
            Built (buildMarkdown sourcePath extracted sigResult)
